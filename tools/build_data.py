"""Builds everything the app and the database share, from one source, so they cannot drift:
  src/data/exercises.json                      the library the app ships with
  supabase/migrations/20261127000100_exercises.sql   the same library as a database seed
  templates/<slug>.json + src/data/templates.json     every built-in program, validated

usage: python3 tools/build_data.py <free-exercise-db dist/exercises.json>
free-exercise-db is public domain (Unlicense): https://github.com/yuhonas/free-exercise-db"""
