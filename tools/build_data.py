def rotation(pattern, rest_suggest=("walking", "mobility")):
    out = []
    for day, item in zip(WEEK, pattern):
        if item is None: out.append({"rest": True, "suggest": list(rest_suggest), "suggested_weekday": day})
        else: out.append({"session": item, "suggested_weekday": day})
    return out

def tpl(slug, title, summary, focus, level, weeks, pattern, equipment, phases, roles, prog, sessions, **extra):
    t = {"schema_version": 1, "slug": slug, "title": title, "summary": summary, "author": "Spotter",
         "focus": focus, "level": level, "weeks": weeks,
         "days_per_week": sum(1 for p in pattern if p), "units": "lb", "equipment": equipment,
         "phases": phases, "rotation": rotation(pattern), "progression": prog, "roles": roles, "sessions": sessions}
    t.update(extra)
    return t

