# The database only needs each library id to exist (sets point at it) plus a few plain facts.
# Names, photos and how-to steps ship inside the app, so the seed stays small: one line per exercise.
#   id | domain, region, load, measure, source as one letter each | equipment | main muscle | name, only if it is not just the id with spaces
def flags(r):
    return ({"strength": "s", "mobility": "m", "cardio": "c"}[r["domain"]] + {"upper": "u", "lower": "l", "core": "c", None: "-"}[r["region"]]
            + ("b" if r["load_type"] == "bodyweight" else "x") + ("s" if r["measure"] == "seconds" else "r") + ("b" if r["source"] == "builtin" else "f"))
lines = []
for r in rows:
    name = "" if r["name"] == r["id"].replace("_", " ") else r["name"]
    line = "|".join([r["id"], flags(r), r["equipment"] or "", (r["primary_muscles"] or [""])[0], name]).rstrip("|")
    assert "\n" not in line and line.count("|") <= 4 and "$seed$" not in line, line
    lines.append(line)
(root / "supabase/migrations/20261127000100_exercises.sql").write_text(
    f"-- Generated by tools/build_data.py. {len(library_raw)} exercises from free-exercise-db (public domain) and {len(builtin)} built in.\n"
    "-- One line each: id | domain region load measure source | equipment | main muscle | name (when it differs from the id).\n"
    "insert into public.exercises (id, name, domain, source, equipment, primary_muscles, region, load_type, measure)\n"
    "select p[1],\n"
    "       coalesce(nullif(p[5], ''), replace(p[1], '_', ' ')),\n"
    "       case substr(p[2], 1, 1) when 's' then 'strength' when 'm' then 'mobility' else 'cardio' end,\n"
    "       case substr(p[2], 5, 1) when 'b' then 'builtin' else 'free-exercise-db' end,\n"
    "       nullif(p[3], ''),\n"
    "       case when coalesce(p[4], '') = '' then '{}'::text[] else array[p[4]] end,\n"
    "       case substr(p[2], 2, 1) when 'u' then 'upper' when 'l' then 'lower' when 'c' then 'core' end,\n"
    "       case substr(p[2], 3, 1) when 'b' then 'bodyweight' else 'external' end,\n"
    "       case substr(p[2], 4, 1) when 's' then 'seconds' else 'reps' end\n"
    "from (select string_to_array(line, '|') as p from regexp_split_to_table($seed$\n" + "\n".join(lines) + "\n$seed$, E'\\n') as line where line <> '') as x\n"
    "on conflict (id) do update set name = excluded.name, domain = excluded.domain, source = excluded.source, equipment = excluded.equipment,\n"
    "  primary_muscles = excluded.primary_muscles, region = excluded.region, load_type = excluded.load_type, measure = excluded.measure;\n")

# ---------------------------------------------------------------- templates
BOOST = {"drop": "drop_set", "ddrop": "double_drop", "rp": "rest_pause", "rps": "rest_pause_stretch",
         "myo": "myo_reps", "lp": "lengthened_partials"}

def rng(s):
    a, b = s.split("-"); return [int(a), int(b)]

def make(phases):
    """Slot helpers bound to a block's phase keys. Reps are given per phase, in order."""
    def slot(key, role, ex, reps, inc=None, boost=None, name=None, **extra):
        reps = reps if isinstance(reps, (list, tuple)) else [reps] * len(phases)
        s = {"key": key, "role": role, "exercise": ex}
        if name: s["display_name"] = name
        s["reps"] = {p: (r if r in ("amrap", "skip") else rng(r)) for p, r in zip(phases, reps)}
        if inc: s["increment"] = inc
        if by_id.get(ex, {}).get("load_type") == "bodyweight" and "load" not in extra: s["load"] = "bodyweight"
        if by_id.get(ex, {}).get("measure") == "seconds": s["measure"] = "seconds"
        if boost: s["intensifier"] = {"type": BOOST[boost], "on": "last_set", "phases": [phases[-1]]}
        e = by_id.get(ex)
        if e and e["primary_muscles"]: s["swap_tags"] = [e["primary_muscles"][0]]
        s.update(extra)
        return s
    def P(key, ex, reps, inc=None, boost=None, name=None, **kw): return slot(key, "primary", ex, reps, inc, boost, name, **kw)
    def A(key, ex, reps, inc=None, boost=None, name=None, **kw): return slot(key, "accessory", ex, reps, inc, boost, name, **kw)
    def F(key, ex, name=None, **kw):
        return slot(key, "finisher", ex, ["amrap"] + ["skip"] * (len(phases) - 1), name=name, load="bodyweight", **kw)
    return P, A, F

def sess(key, title, subtitle, slots):
    for s in slots: s["key"] = f"{key}.{s['key']}"
    return {"key": key, "title": title, "subtitle": subtitle, "slots": slots}

