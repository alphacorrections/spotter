# ---------------------------------------------------------------- validate
schema = json.loads((root / "templates/program-template.schema.json").read_text())
Draft202012Validator.check_schema(schema)

def problems_in(t):
    out = [f"shape: {'/'.join(map(str, e.path))}: {e.message}" for e in Draft202012Validator(schema).iter_errors(t)]
    if out: return out
    phases = [p["key"] for p in t["phases"]]
    covered = [w for p in t["phases"] for w in range(p["weeks"][0], p["weeks"][1] + 1)]
    if covered != list(range(1, t["weeks"] + 1)): out.append(f"phases cover weeks {covered}, block has 1..{t['weeks']}")
    sessions = {s["key"] for s in t["sessions"]}
    in_rot = [r["session"] for r in t["rotation"] if "session" in r]
    out += [f"rotation names unknown session {k}" for k in in_rot if k not in sessions]
    out += [f"session {k} is never scheduled" for k in sessions if k not in in_rot]
    if len(in_rot) != t["days_per_week"]: out.append("rotation and days_per_week disagree")
    seen = set()
    for s in t["sessions"]:
        letters = collections.Counter(sl["superset"] for sl in s["slots"] if "superset" in sl)
        out += [f"{s['key']}: superset {l} has one slot" for l, n in letters.items() if n < 2]
        for sl in s["slots"]:
            k = sl["key"]
            if k in seen: out.append(f"duplicate slot key {k}")
            seen.add(k)
            if not k.startswith(s["key"] + "."): out.append(f"slot {k} not prefixed with its session")
            if set(sl["reps"]) != set(phases): out.append(f"slot {k}: reps for {sorted(sl['reps'])}, phases are {phases}")
            for ph in sl.get("intensifier", {}).get("phases", []):
                if ph not in phases: out.append(f"slot {k}: intensifier names unknown phase {ph}")
            for ex in [sl["exercise"]] + [a["exercise"] for a in sl.get("alternates", [])]:
                if ex not in by_id: out.append(f"slot {k}: exercise {ex} is not in the library")
            e = by_id.get(sl["exercise"])
            if e and e["equipment"] not in ("none", "other") and e["equipment"] not in t["equipment"] + (["barbell"] if "landmine" in t["equipment"] else []):
                out.append(f"slot {k}: needs {e['equipment']}, which the template's equipment list leaves out")
            loaded = sl.get("load", "external") != "bodyweight"
            prog = sl.get("progression", t["progression"])
            if loaded and prog["type"] in ("double_progression", "top_set_backoff") and "increment" not in sl:
                out.append(f"slot {k}: loaded slot with no increment")
    return out

bad = 0
for t in templates:
    t["progression"] = {k: v for k, v in t["progression"].items() if v is not None}
    ps = problems_in(t)
    slots = sum(len(s["slots"]) for s in t["sessions"])
    print(f"{'FAIL' if ps else 'ok  '} {t['slug']:<36} {t['focus']:<11} {t['days_per_week']}d  {len(t['sessions'])} sessions  {slots} slots")
    for p in ps: print("       -", p)
    bad += bool(ps)
    (root / "templates" / f"{t['slug']}.json").write_text(json.dumps(t, indent=2, ensure_ascii=False) + "\n")
(root / "src/data/templates.json").write_text(json.dumps(templates, ensure_ascii=False, separators=(",", ":")))
